  const MAX_PHRASE = 4;

  // char -> syllable, inverted from the grouped table once at load.
  const READ = new Map();
  for (const syl in READINGS) {
    for (const ch of READINGS[syl]) READ.set(ch, syl);
  }

  const PHRASE = new Map();
  for (const seq in PHRASES) PHRASE.set(seq, PHRASES[seq]);

  const DI = "地";

  /**
   * One maximal run of Han characters -> space-separated pinyin syllables.
   * Characters with no reading (unassigned codepoints, the dozen Japan-only
   * compatibility ideographs) are skipped rather than emitted as undefined.
   */
  function romanize(word) {
    if (!word) return "";
    const chars = Array.from(word);
    const out = [];
    let i = 0;

    while (i < chars.length) {
      // Longest phrase match wins: 银行卡 before 银行, 银行 before 行.
      let hit = null;
      let len = Math.min(MAX_PHRASE, chars.length - i);
      for (; len >= 2; len--) {
        hit = PHRASE.get(chars.slice(i, i + len).join(""));
        if (hit) break;
      }
      if (hit) {
        out.push(hit);
        i += len;
        continue;
      }

      const ch = chars[i];

      // A reduplicated adjective followed by 地 makes it the adverbial particle
      // "de", not the noun "di": 慢慢地 -> "man man de", but 各地 -> "ge di".
      if (ch === DI && i >= 2 && chars[i - 1] === chars[i - 2] && chars[i - 1] !== DI) {
        out.push("de");
        i += 1;
        continue;
      }

      const syl = READ.get(ch);
      if (syl) out.push(syl);
      i += 1;
    }

    return out.join(" ");
  }

